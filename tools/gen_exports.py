#!/usr/bin/env python3
"""Generate the export table and jump thunks for the winmm.dll proxy.

Reads `objdump -p` output of Wine's builtin winmm.dll from stdin and writes:
  <out>/winmm.def   module definition with the same names and ordinals
  <out>/thunks.S    one jump thunk per export, through a pointer table
  <out>/exports.h   table of (ordinal, name) used to resolve the real functions

Exports listed in OVERRIDDEN are implemented in C by the proxy and get no thunk.
"""
import re
import sys
from pathlib import Path

OVERRIDDEN = {
    "midiInMessage", "midiOutMessage",
    "midiInGetDevCapsA", "midiInGetDevCapsW", "midiOutGetDevCapsA", "midiOutGetDevCapsW",
}

ROW = re.compile(r"^\s*\[\s*\d+\]\s+\+base\[\s*(\d+)\]\s+[0-9a-fA-F]+\s+(\S+)\s*$")
EAT_SIZE = re.compile(r"^\s*Export Address Table\s+([0-9a-fA-F]+)\s*$")
BASE = re.compile(r"Ordinal Base\s+(\d+)")


def parse(text):
    named = {}
    eat_size = None
    base = None
    in_names = False
    for line in text.splitlines():
        if eat_size is None and (m := EAT_SIZE.match(line)):
            eat_size = int(m.group(1), 16)
        if base is None and (m := BASE.search(line)):
            base = int(m.group(1))
        if "[Ordinal/Name Pointer] Table" in line:
            in_names = True
            continue
        if in_names:
            if m := ROW.match(line):
                named[int(m.group(1))] = m.group(2)
            elif line.strip() == "" and named:
                break
    if eat_size is None or base is None or not named:
        sys.exit("could not parse export table")
    exports = []
    for ordinal in range(base, base + eat_size):
        exports.append((ordinal, named.get(ordinal)))
    return exports


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    exports = parse(sys.stdin.read())

    thunked = [(o, n) for o, n in exports if n not in OVERRIDDEN]

    deflines = ["LIBRARY winmm.dll", "EXPORTS"]
    for o, n in exports:
        if n is None:
            deflines.append(f"    ord_{o} @{o} NONAME")
        else:
            deflines.append(f"    {n} @{o}")
    (out / "winmm.def").write_text("\n".join(deflines) + "\n")

    asm = [".text"]
    for i, (o, n) in enumerate(thunked):
        sym = n or f"ord_{o}"
        asm += [f".globl {sym}", f"{sym}:", f"    jmp *real_procs+{8 * i}(%rip)"]
    (out / "thunks.S").write_text("\n".join(asm) + "\n")

    rows = [f'    {{{o}, {("\"" + n + "\"") if n else "NULL"}}},' for o, n in thunked]
    header = [
        "/* Generated by tools/gen_exports.py. Do not edit. */",
        f"#define REAL_PROC_COUNT {len(thunked)}",
        "static const struct { WORD ordinal; const char *name; } real_exports[] = {",
        *rows,
        "};",
    ]
    (out / "exports.h").write_text("\n".join(header) + "\n")
    print(f"{len(exports)} exports, {len(thunked)} thunks", file=sys.stderr)


if __name__ == "__main__":
    main()
